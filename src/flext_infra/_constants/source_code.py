    @staticmethod
    def compile_from_module_paren_open(module_name: str) -> t.RegexPattern:
        """Compile ``^from <module_name> import (`` for parenthesized-import detection."""
        return re.compile(rf"^from\s+{re.escape(module_name)}\s+import\s+\(")

