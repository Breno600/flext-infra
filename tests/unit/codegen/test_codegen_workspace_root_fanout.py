"""Conform is the single owner of the workspace-root Makefile with member fan-out.

The workspace-root profile must be generated by ``codegen conform`` (the single
Makefile owner for every profile) and its generic gate verbs must fan out across
declared members through the generic ``flext-infra workspace orchestrate``
primitive, never through hardcoded per-project logic.
"""

from __future__ import annotations

from pathlib import Path

from flext_infra import c, config, m
from flext_infra.codegen.conform import FlextInfraCodegenConform
from flext_tests import tm
from tests import u as test_u


class TestsCodegenWorkspaceRootFanout:
    def test_conform_owns_workspace_root_makefile(self) -> None:
        """The single Makefile render entry includes the workspace-root profile."""
        makefile_entries = tuple(
            entry
            for entry in config.Infra.codegen.templates.entries
            if entry.destination == c.Infra.MAKEFILE_FILENAME
        )
        tm.that(makefile_entries, len=1)
        tm.that(makefile_entries[0].profiles, has=c.Infra.MakeProfile.WORKSPACE_ROOT)

    def test_workspace_root_gate_verbs_fan_out_via_orchestrator(
        self, tmp_path: Path
    ) -> None:
        """Generated workspace-root check/test route through workspace orchestrate."""
        rendered = _render_root_makefile(tmp_path)
        tm.that(rendered, has="$(WORKSPACE_ORCHESTRATE) --verb check")
        tm.that(rendered, has="$(WORKSPACE_ORCHESTRATE) --verb test")
        tm.that(rendered, has="MAKE_PROFILE := workspace-root")
        tm.that(rendered, has="$(FLEXT_INFRA_PYTHON) -m flext_infra")


def _render_root_makefile(tmp_path: Path) -> str:
    """Render base/Makefile.j2 from a typed workspace-root fixture."""
    repository = test_u.Tests.repository_ref("workspace-root-fixture")
    workspace = m.Infra.WorkspaceSpec(
        version=c.Infra.WORKSPACE_MANIFEST_VERSION,
        name=repository.name,
        repository=repository,
        project=m.Infra.ProjectSpec(
            package_name=repository.distribution.replace("-", "_"),
            class_stem="FixtureWorkspace",
            namespace="FixtureWorkspace",
            constant_name=repository.name,
            namespace_attribute="fixture_workspace",
            alias="fixture_workspace",
            environment_prefix="FIXTURE_WORKSPACE_",
            description="Fixture workspace",
            version="0.12.0.dev0",
            license="MIT",
            author_name="FLEXT Team",
            author_email="team@flext.dev",
            upstream="flext_cli",
            homepage=repository.url.removesuffix(".git"),
            documentation=repository.url.removesuffix(".git"),
            workspace_root_rel=".",
            year=2026,
        ),
    )
    workspace_root = tmp_path / "workspace"
    request = m.Infra.CodegenConformRequest(
        root=workspace_root,
        what=c.Infra.CodegenConformSurface.MAKEFILE,
        scope=c.Infra.CodegenConformScope.SELF,
        mode=c.Infra.CodegenConformMode.CHECK,
    )
    plan = tm.ok(
        FlextInfraCodegenConform(
            workspace_root=workspace_root, request=request, initial_workspace=workspace
        ).plan(request)
    )
    makefile_plans = tuple(
        fp for fp in plan.files if Path(fp.path).name == c.Infra.MAKEFILE_FILENAME
    )
    tm.that(makefile_plans, len=1)
    rendered: str = makefile_plans[0].rendered
    return rendered


__all__: tuple[str, ...] = ()
